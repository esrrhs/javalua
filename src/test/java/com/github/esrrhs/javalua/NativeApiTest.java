    @TestFactory
    List<DynamicTest> cApiMatchesReference() {
        List<DynamicTest> tests = new ArrayList<>();
        String path = fixture();
        Assumptions.assumeTrue(path != null, "跳过 C API 用例：" + skipReason);
        for (String[] c : CASES) {
            StringBuilder body = new StringBuilder();
            for (int i = 1; i < c.length; i++) {
                body.append(c[i]).append('\n');
            }
            /*
             * 回溯是<b>脚本打印出来的</b>那几条（{@code luaL_traceback}）得走
             * {@code assertFullMatches}：{@code assertMatches} 会从第一个
             * {@code stack traceback:} 处把后面全砍掉，而这里后面还有脚本自己的
             * 输出——砍掉的那一段一条分歧也发现不了（见 {@link Diff#assertMatches}）。
             */
            boolean full = FULL_MATCH.contains(c[0]);
            String head = PRE.replace("@SO@", path);
            String plain = head + body;
            tests.add(DynamicTest.dynamicTest("C API: " + c[0],
                    () -> run(full, plain, c[0])));
            /*
             * <b>第二遍：同一批语料塞进协程再跑一次。</b>
             * <p>
             * 第 7 条那条经验（registry 及 {@code _LOADED} / {@code _G} 是
             * {@code global_State} 级的）说的是「这类 bug 只在协程里现形」，
             * 而 C API 那一侧的协程相关面比纯 Lua 更大：{@code ci} 链多一层、
             * {@code lua_getstack} 数出来的层级不一样、{@code luaL_where}
             * 拿到的行可能落在协程体里、{@code lua_pushthread} 不再答真、
             * {@code lua_isyieldable} 反过来了。主线程上全绿不代表这里绿。
             */
            String inCo = head + "coroutine.wrap(function()\n" + body
                    + "end)()\n";
            if (!NO_CO.contains(c[0])) {
                tests.add(DynamicTest.dynamicTest("C API（协程里）: " + c[0],
                        () -> run(full, inCo, c[0])));
            }
        }
        return tests;
    }

    /**
     * 抛出来的异常要带上用例名——动态用例在 surefire 报告里全叫
     * {@code cApiMatchesReference}，不带上就只能靠「第几条」去数。
     */
    private static void run(boolean full, String src, String name) {
        try {
            if (full) {
                Diff.assertFullMatches(src);
            } else {
                Diff.assertMatches(src);
            }
        } catch (org.opentest4j.TestAbortedException e) {
            throw e;
        } catch (Throwable t) {
            throw new AssertionError("用例「" + name + "」抛了 " + t, t);
        }
    }

    private static synchronized String fixture() {
        if (so != null) {
            return so;
        }
        if (!NativeBridge.AVAILABLE) {
            skipReason = "native 层没装起来: " + NativeBridge.LOAD_ERROR;
            return null;
        }
        String cc = firstOf("cc", "gcc", "clang");
        if (cc == null) {
            skipReason = "PATH 里没有 C 编译器";
            return null;
        }
        try {
            File dir = new File(Diff.SCRATCH);
            if (!dir.isDirectory() && !dir.mkdirs()) {
                return null;
            }
            File c = new File(dir, "api.c");
            File lib = new File(dir, "api.so");
            Files.write(c.toPath(), C.getBytes(StandardCharsets.UTF_8));
            List<List<String>> cmds = new ArrayList<>();
            cmds.add(Arrays.asList(cc, "-shared", "-fPIC", "-undefined",
                    "dynamic_lookup", "-I", "native/lua", "-o", lib.getPath(),
                    c.getPath()));
            cmds.add(Arrays.asList(cc, "-shared", "-fPIC", "-I", "native/lua",
                    "-o", lib.getPath(), c.getPath()));
            boolean ok = false;
            for (List<String> cmd : cmds) {
                Process p = new ProcessBuilder(cmd)
                        .redirectErrorStream(true).start();
                if (p.waitFor() == 0 && lib.isFile()) {
                    ok = true;
                    break;
                }
            }
            if (!ok) {
                skipReason = "编译扩展失败（" + cc + "）";
            }
            so = ok ? lib.getAbsolutePath() : null;
        } catch (Exception e) {
            skipReason = "编译扩展失败: " + e;
            so = null;
        }
        return so;
    }

    private static String firstOf(String... names) {
        for (String n : names) {
            for (String d : System.getenv("PATH").split(File.pathSeparator)) {
                if (new File(d, n).canExecute()) {
                    return n;
                }
            }
        }
        return null;
    }
