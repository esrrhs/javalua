local n = require('lpeg')
local co = coroutine.create(function()
  return (n.C(n.P(1)) / function(c) coroutine.yield(c); return c end):match('a')
end)
local ok, err = coroutine.resume(co)
assert(not ok and type(err) == 'string')
assert(err:find('yield across a C%-call boundary'))
assert(coroutine.status(co) == 'dead')
assert(n.P('z'):match('z') == 2)
print(ok, err:match('attempt to yield.*'))
