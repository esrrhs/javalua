local n = require('lpeg')
assert(type(n.P) == 'function' and type(n.match) == 'function')
assert(n == require('lpeg'))
assert(coroutine.wrap(function() return require('lpeg') end)() == n)
local path = assert(package.searchpath('lpeg', package.cpath))
local loader = assert(package.loadlib(path, 'luaopen_lpeg'))
assert(type(loader()) == 'table')
local f, msg, where = package.loadlib(path, 'luaopen_does_not_exist')
assert(f == nil and type(msg) == 'string' and where == 'init')
print(n.version)
